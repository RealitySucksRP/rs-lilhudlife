"""Rebuild the shipped vehicle artwork index after adding or removing images."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
directory = root / 'html/assets/vehicles'
files = sorted(p.name for p in directory.iterdir() if p.is_file() and p.suffix.lower() in ('.png', '.webp'))
source = '''// Generated by tools/build_vehicle_art_index.py; rebuild after changing vehicle artwork.
(function () {
    const files = new Set(%s);
    window.RSVehicleArtPaths = function (names) {
        const paths = [];
        for (const name of names) {
            for (const extension of ['png', 'webp']) {
                const filename = name + '.' + extension;
                if (files.has(filename)) paths.push('assets/vehicles/' + filename);
            }
        }
        return paths;
    };
})();
''' % json.dumps(files, separators=(',', ':'))
(root / 'html/js/vehicle-art-index.js').write_text(source, encoding='utf-8')
print(f'Indexed {len(files)} vehicle images.')
